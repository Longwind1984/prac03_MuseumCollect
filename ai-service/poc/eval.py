#!/usr/bin/env python3
"""
eval.py — Leave-one-out retrieval eval on the PoC index.

For each item in items.json/embeddings.npy:
  - hold it out
  - query the rest with its embedding
  - record top-1 match id and top-5 set
  - is_correct@1 = (top1.id == self.id)  — degenerate when 1 image/artifact
  - is_correct@5 = (self.id ∈ top5)

Reports P@1, P@5 overall + per-dynasty breakdown + failure cases.

Honest limitation: with only 1 image per artifact, leave-one-out degenerates —
the held-out item's id will never appear in the remaining index, so a strict
match is by definition impossible. We instead report "intra-class top-1 match"
as a proxy: did the model return the SAME-CLASS (same form_subtype + same dynasty)
sibling closest? That's the v0 honest metric. Full per-artifact eval requires
≥2 images per item, blocked by current data (see README "Tradeoff 3").
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np


def cosine_topk(query: np.ndarray, corpus: np.ndarray, k: int) -> np.ndarray:
    """corpus is L2-normalized (N,D), query is (D,). Returns top-k indices descending similarity."""
    sims = corpus @ query
    return np.argsort(-sims)[:k]


def evaluate(embeddings: np.ndarray, items: list[dict], top_k: int = 5) -> dict:
    n = len(items)
    correct_at_1 = 0
    correct_at_5 = 0
    intra_class_at_1 = 0
    per_dynasty = defaultdict(lambda: {"n": 0, "p1": 0, "p5": 0, "intra1": 0})
    failures = []

    for i, item in enumerate(items):
        mask = np.ones(n, dtype=bool)
        mask[i] = False
        corpus = embeddings[mask]
        corpus_items = [items[j] for j in range(n) if j != i]
        query = embeddings[i]
        topk_idx = cosine_topk(query, corpus, top_k)
        topk_items = [corpus_items[j] for j in topk_idx]
        top1 = topk_items[0]

        is_p1 = top1["id"] == item["id"]
        is_p5 = any(t["id"] == item["id"] for t in topk_items)
        is_intra1 = top1.get("dynasty") == item.get("dynasty")

        correct_at_1 += int(is_p1)
        correct_at_5 += int(is_p5)
        intra_class_at_1 += int(is_intra1)

        dyn = item.get("dynasty") or "未知"
        per_dynasty[dyn]["n"] += 1
        per_dynasty[dyn]["p1"] += int(is_p1)
        per_dynasty[dyn]["p5"] += int(is_p5)
        per_dynasty[dyn]["intra1"] += int(is_intra1)

        if not is_p5:
            failures.append({
                "query_id": item["id"],
                "query_name": item.get("name"),
                "query_dynasty": item.get("dynasty"),
                "top1_id": top1["id"],
                "top1_name": top1.get("name"),
                "top1_dynasty": top1.get("dynasty"),
            })

    return {
        "n": n,
        "p_at_1": correct_at_1 / n if n else 0.0,
        "p_at_5": correct_at_5 / n if n else 0.0,
        "intra_class_at_1": intra_class_at_1 / n if n else 0.0,
        "per_dynasty": {k: {"n": v["n"], "p1": v["p1"] / v["n"] if v["n"] else 0,
                            "p5": v["p5"] / v["n"] if v["n"] else 0,
                            "intra1": v["intra1"] / v["n"] if v["n"] else 0}
                        for k, v in per_dynasty.items()},
        "failures": failures,
    }


def write_report(report_path: Path, metrics: dict, model_name: str):
    n = metrics["n"]
    lines = [
        "# Eval Report — CLIP Retrieval PoC",
        "",
        f"> Auto-generated by `eval.py` · {n} items · model: `{model_name}`",
        "",
        "## Headline metrics",
        "",
        "| Metric | Value | Roadmap §6.3 target |",
        "|---|---|---|",
        f"| P@1 (strict id match) | {metrics['p_at_1']:.3f} | ≥ 0.40 |",
        f"| P@5 (id in top-5) | {metrics['p_at_5']:.3f} | ≥ 0.60 |",
        f"| Intra-class P@1 (proxy, see eval.py docstring) | {metrics['intra_class_at_1']:.3f} | — |",
        "",
        "## Per-dynasty breakdown",
        "",
        "| Dynasty | N | P@1 | P@5 | Intra-class P@1 |",
        "|---|---|---|---|---|",
    ]
    for dyn, m in sorted(metrics["per_dynasty"].items(), key=lambda kv: -kv[1]["n"]):
        lines.append(f"| {dyn} | {m['n']} | {m['p1']:.2f} | {m['p5']:.2f} | {m['intra1']:.2f} |")

    lines += ["", "## Failure cases (top-5 miss)", ""]
    if not metrics["failures"]:
        lines.append("_None — all queries hit top-5 (or N too small to fail). Inspect manually._")
    else:
        lines.append("| Query | → Top-1 | Same dynasty? |")
        lines.append("|---|---|---|")
        for f in metrics["failures"][:20]:
            same = "✓" if f["query_dynasty"] == f["top1_dynasty"] else "✗"
            lines.append(f"| {f['query_name']} ({f['query_id']}, {f['query_dynasty']}) | "
                         f"{f['top1_name']} ({f['top1_id']}, {f['top1_dynasty']}) | {same} |")
        if len(metrics["failures"]) > 20:
            lines.append(f"| _…and {len(metrics['failures']) - 20} more_ |  |  |")

    lines += [
        "",
        "## Interpretation",
        "",
        "Per `ai-roadmap.md §6.3`, this PoC is **Phase 1 floor**, not production target. Read the per-dynasty",
        "table for class imbalance signals — if Shang ≫ Western Zhou in N, the per-dynasty P@5 comparison",
        "is dominated by sample size, not retrieval quality.",
        "",
        "**Intra-class P@1** is the more meaningful metric for this 1-image-per-artifact regime: 'did the",
        "model return the same-dynasty sibling as nearest?' If this number is ≥ 0.60 we have evidence the",
        "embedding carries dynasty-level structure; ≥ 0.80 means form_subtype is also encoded.",
        "",
        "## Next steps",
        "",
        "1. If headline P@1 < 0.30, examine `image_urls[0]` quality — many Wikimedia thumbs are",
        "   line-drawings/rubbings, not photographs, breaking CLIP's training distribution.",
        "2. Bootstrap a Tier-2 set (5-10 priority artifacts × 3 angles each) and re-eval; expect P@1 to",
        "   become meaningful only with ≥2 images/artifact.",
        "3. Phase 2 (DINOv2 ensemble + OCR) blocked until P@1 ≥ 0.40 on Tier-2.",
    ]
    report_path.write_text("\n".join(lines), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--embeddings", type=Path, default=Path("embeddings.npy"))
    ap.add_argument("--items", type=Path, default=Path("items.json"))
    ap.add_argument("--report", type=Path, default=Path("eval-report.md"))
    ap.add_argument("--model-name", default="OpenCLIP ViT-B/32 (openai)")
    args = ap.parse_args()

    embeddings = np.load(args.embeddings)
    items = json.loads(args.items.read_text(encoding="utf-8"))
    assert len(embeddings) == len(items), f"length mismatch: {len(embeddings)} vs {len(items)}"

    print(f"Evaluating {len(items)} items, top-5 retrieval…")
    metrics = evaluate(embeddings, items, top_k=5)
    print(f"  P@1 = {metrics['p_at_1']:.3f} | P@5 = {metrics['p_at_5']:.3f} | "
          f"intra-class P@1 = {metrics['intra_class_at_1']:.3f}")

    write_report(args.report, metrics, args.model_name)
    print(f"Report → {args.report}")


if __name__ == "__main__":
    main()
